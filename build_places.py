"""
Build web/places.js (the town list for index.html).

Usage:
    python build_places.py                      # fetch fresh data from the APSRTC API
    python build_places.py places.json svc.json # use saved fetchAllUniquePlaces / servicesnumbers/all JSON

Output row format: [placeId, linkPlaceId(0 if same), name, mandal, district, lat, lon, flags]
flags: 1 = mandal headquarters (name == mandal), 2 = depot town
"""
import json
import re
import sys
from pathlib import Path
from urllib.request import Request, urlopen

API = "https://utsappapicached01.apsrtconline.in/uts-vts-api"
HEADERS = {
    "Accept": "application/json",
    "userId": "1363789069449",
    "x-api-key": "53693855434468454E714A596D44457A586975414F573833334833596A584D3333735938444A69357131303D",
}


def get(path: str) -> dict:
    with urlopen(Request(API + path, headers=HEADERS), timeout=60) as r:
        return json.loads(r.read())


def main() -> None:
    if len(sys.argv) == 3:
        places = json.loads(Path(sys.argv[1]).read_text())
        services = json.loads(Path(sys.argv[2]).read_text())
    else:
        places = get("/mappedplaces/fetchAllUniquePlaces")
        services = get("/servicesnumbers/all")

    depots = {
        re.sub(r"[-\s]+\d+$", "", s["serviceDocId"].rsplit("_", 1)[-1].strip().upper())
        for s in services["data"]
    }

    rows = []
    for p in places["miniServicePlaces"]:
        try:
            lat, lon = float(p.get("latitude") or 0), float(p.get("longitude") or 0)
        except (TypeError, ValueError):
            continue
        if not (lat and lon):
            continue
        name = (p.get("placeName") or "").strip().upper()
        mandal = (p.get("mandalName") or "").strip().upper()
        flags = (1 if name and name == mandal else 0) | (2 if name in depots else 0)
        pid = int(p["placeId"])
        link = int(p.get("linkPlaceId") or pid)
        rows.append([pid, 0 if link == pid else link, name, mandal, (p.get("district") or "").strip().upper(),
                     round(lat, 5), round(lon, 5), flags])

    rows.sort(key=lambda r: r[2])
    out = Path(__file__).with_name("places.js")
    out.write_text("// generated by build_places.py\nwindow.PLACES=" + json.dumps(rows, separators=(",", ":")) + ";\n")
    print(f"{len(rows)} places, {sum(r[7] & 1 > 0 for r in rows)} mandal HQs, "
          f"{sum(r[7] & 2 > 0 for r in rows)} depot towns ({len(depots)} depot names) -> {out} "
          f"({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
